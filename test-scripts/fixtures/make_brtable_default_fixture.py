#!/usr/bin/env python3
"""Regenerate the committed `br_table` default-target fixture (`brtable_default.wasm`).

Regression fixture for REPORT-R5-BRTABLE.md. It is a minimal module whose single exported
function `default_branch` contains a `br_table` with **exactly** `MAX_BR_TABLE_CASES` (1024)
explicit case labels whose target is the end of the *inner* block, and a default target that is
the end of the *outer* block:

    (func (export "default_branch") (result i32)
      (block                    ;; outer
        (block                  ;; inner
          i32.const 1024        ;; out-of-range index -> DEFAULT target
          br_table 0 0 ... 0 1  ;; 1024 x label 0 (inner end), default label 1 (outer end)
        )
        i32.const 1
        return)                 ;; reached when a case matches
      i32.const 2)              ;; reached via the DEFAULT target

The value pushed (1024) is >= the number of cases, so the spec requires the default target to be
taken and the function to return **2**. With the pre-fix expansion cap the default label was
dropped (the cap check truncated at 1024 labels *including* the default), so the modelled switch
had no default and fell through to `i32.const 1` -> return 1. `test-scripts/check-brtable-default.ps1`
imports this fixture with the pinned install and asserts the emulated return is 2.

This fixture is byte-identical to the authoritative review artefact
`D:\\code\\Ghidra-WASM\\build\\release-review-sol\\brcap.wasm` (generated by that directory's
`generate.py`); `make_brtable_default_fixture.py` is the in-tree, self-contained copy so the
fixture can be regenerated without the review workspace.

Usage: python test-scripts/fixtures/make_brtable_default_fixture.py [output-dir]
Default output dir is the directory containing this script.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from wasm_probe_lib import *  # noqa: F401,F403

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
set_output_dir(OUT)

RETURN = b"\x0f"
MAX_BR_TABLE_CASES = 1024

# br_table encoding: opcode, ULEB vector *count*, that many case label indices, then the default
# label index. (wasm_probe_lib.br_table() packs the default into the vector length, which is not
# the spec encoding, so build the bytes explicitly here - the same way the review artefact did.)
# All 1024 cases target label 0 (the inner block's `end`); the default targets label 1 (the outer
# block's `end`).
BR_TABLE = (b"\x0e" + uleb(MAX_BR_TABLE_CASES) + bytes(MAX_BR_TABLE_CASES) + uleb(1))

# inner block: push the out-of-range index, then the br_table above.
INNER = block(0x40, i32_const(MAX_BR_TABLE_CASES) + BR_TABLE)
# outer block: after the inner block, return 1 (reached only if a case matches).
OUTER = block(0x40, INNER + i32_const(1) + RETURN)
# function body: after the outer block, return 2 (reached via the default target).
BODY = OUTER + i32_const(2) + END

write("brtable_default.wasm", module(
    type_section(functype([], [I32])),
    func_section([0]),
    export_section([("default_branch", 0, 0)]),
    code_section([BODY]),
))
print("Generated brtable_default.wasm")
